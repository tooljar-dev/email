// Builds the npm package "is-temp-email" in ./npm from ./data. Usage: npm run npm:build
// Writes npm/data.js, npm/package.json, npm/LICENSE and npm/DATA-LICENSES.md (all generated).
// The version is the published version + 1 (patch). `dataHash` lets the release job skip
// publishing when the data did not change.
import { createHash } from "node:crypto";
import { copyFile, readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const NAME = "is-temp-email";

const domains = (await readFile(new URL("data/domains.txt", root), "utf8")).trim();
const meta = JSON.parse(await readFile(new URL("data/meta.json", root), "utf8"));
const allow = (await readFile(new URL("data/allow.txt", root), "utf8"))
  .split("\n")
  .map((line) => line.replace(/#.*/, "").trim().split(/\s+/))
  .filter(([domain, kind]) => domain && (kind === "provider" || kind === "forwarding"))
  .map(([domain, kind]) => `${domain}\t${kind}`)
  .join("\n");
const sources = meta.sources.map((s) => s.id);

const dataHash = createHash("sha256")
  .update(`${domains}\n--\n${allow}\n--\n${sources.join(",")}`)
  .digest("hex")
  .slice(0, 16);

const dataJs = `// Generated by scripts/build-npm.mjs from data/ (updated ${meta.updated}). Do not edit.
export const UPDATED = ${JSON.stringify(meta.updated)};
export const SOURCES = ${JSON.stringify(sources)};
export const ALLOW = ${JSON.stringify(allow)};
export const DOMAINS = ${JSON.stringify(domains)};
`;
await writeFile(new URL("npm/data.js", root), dataJs);

let version = "1.0.0";
let publishedHash = null;
try {
  const res = await fetch(`https://registry.npmjs.org/${NAME}/latest`, {
    signal: AbortSignal.timeout(15000),
  });
  if (res.ok) {
    const latest = await res.json();
    publishedHash = latest.dataHash ?? null;
    const [major, minor, patch] = latest.version.split(".").map(Number);
    version = `${major}.${minor}.${patch + 1}`;
  }
} catch {
  // Offline: build 1.0.0 locally; the release job always has network.
}

const pkg = {
  name: NAME,
  version,
  description: `Is this email address temp mail? Offline check against ${meta.domains.toLocaleString("en-US")} disposable email domains from 5 open lists, with Gmail clean-up and an optional live check.`,
  keywords: [
    "disposable-email",
    "temp-mail",
    "temporary-email",
    "burner-email",
    "throwaway-email",
    "email-validation",
    "fake-email",
    "signup",
    "gmail-normalize",
  ],
  homepage: "https://email.tooljar.dev",
  bugs: "https://github.com/tooljar-dev/email/issues",
  repository: {
    type: "git",
    url: "git+https://github.com/tooljar-dev/email.git",
    directory: "npm",
  },
  license: "MIT",
  author: "Saba Janelidze (https://www.sabajanelidze.com)",
  type: "module",
  exports: { ".": { types: "./index.d.ts", default: "./index.js" } },
  main: "./index.js",
  types: "./index.d.ts",
  files: ["index.js", "index.d.ts", "data.js", "DATA-LICENSES.md"],
  engines: { node: ">=18" },
  sideEffects: false,
  dataHash,
  dataUpdated: meta.updated,
};
await writeFile(new URL("npm/package.json", root), `${JSON.stringify(pkg, null, 2)}\n`);
await copyFile(new URL("LICENSE", root), new URL("npm/LICENSE", root));
await copyFile(new URL("data/LICENSES.md", root), new URL("npm/DATA-LICENSES.md", root));

const changed = publishedHash !== dataHash;
console.log(`${NAME}@${version}: data ${dataHash} (${changed ? "changed" : "same as published"})`);
if (process.env.GITHUB_OUTPUT) {
  await writeFile(process.env.GITHUB_OUTPUT, `changed=${changed}\nversion=${version}\n`, {
    flag: "a",
  });
}
